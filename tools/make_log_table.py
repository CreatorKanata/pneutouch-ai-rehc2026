"""Write the log2 table of the chip's fast logarithm (fast_log.c).

T[i] = log2(1 + i/256) for i = 0..256, as float32 with 9 significant digits
(enough to round-trip a float32), so the C literal and the PC mirror
(tools/feature_select.py) hold the same bits. T[0] = 0 and T[256] = 1 exactly.

Run:
    .venv/bin/python tools/make_log_table.py
"""
import math
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
HEADER = ROOT / 'src/pneutouch-solist/S_PneuTouch/fast_log_table.h'
STEPS = 256
PER_LINE = 6


def literals():
    """257 decimal strings, one per table entry."""
    return [f'{float(np.float32(math.log2(1.0 + i / STEPS))):.9g}' for i in range(STEPS + 1)]


def table():
    """The same entries as a float32 array (what the C compiler stores)."""
    return np.array([np.float32(text) for text in literals()], dtype=np.float32)


def header_text():
    entries = [f'{text}f' if ('.' in text or 'e' in text) else f'{text}.0f' for text in literals()]
    rows = [', '.join(entries[i:i + PER_LINE]) for i in range(0, len(entries), PER_LINE)]
    body = ',\n    '.join(rows)
    return ('/* Generated by tools/make_log_table.py: do not edit.\n'
            '   log2(1 + i/256), i = 0..256, float32 (9 significant digits). */\n'
            '#ifndef PNEU_FAST_LOG_TABLE_H\n#define PNEU_FAST_LOG_TABLE_H\n'
            f'static const float pneu_log2_table[{STEPS + 1}] = {{\n    {body}\n}};\n#endif\n')


def main():
    HEADER.write_text(header_text(), encoding='utf-8')
    print(f'wrote {HEADER.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
