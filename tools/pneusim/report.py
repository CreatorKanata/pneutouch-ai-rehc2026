"""Figures, summary table and parameter dump for a simulator run."""
import json

import numpy as np
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt  # noqa: E402

from . import calibrate, features, scenarios  # noqa: E402

COLORS = plt.get_cmap('tab10')


def plot_waveforms(path, name, campaign):
    fig, ax = plt.subplots(figsize=(8, 4.5))
    t = campaign.time
    for z in range(1, 8):
        y = campaign.counts[campaign.zones == z] / 1000
        mu, sd = y.mean(axis=0), y.std(axis=0)
        ax.plot(t, mu, color=COLORS(z - 1), label=scenarios.ZONE_NAMES[z])
        ax.fill_between(t, mu - sd, mu + sd, color=COLORS(z - 1), alpha=0.15)
    ax.set(xlabel='time [s] (press starts at 0.5 s)', ylabel='delta counts / 1000',
           title=f'{name}: mean +/- 1 sd sensor waveform per zone (40 SPS)')
    ax.legend(ncol=2, fontsize=8)
    ax.grid(alpha=0.3)
    fig.tight_layout()
    fig.savefig(path, dpi=120)
    plt.close(fig)


def top_two(sep):
    ranked = sorted(sep['eta_squared'].items(), key=lambda kv: kv[1], reverse=True)
    return [k for k, _ in ranked[:2]]


def plot_features(path, name, sep):
    fig, ax = plt.subplots(figsize=(6, 5))
    names = top_two(sep)
    cols = [features.FEATURES.index(k) for k in names]
    for z in range(1, 8):
        pts = sep['x'][sep['zones'] == z]
        if len(pts):
            ax.scatter(np.exp(pts[:, cols[0]]), np.exp(pts[:, cols[1]]), s=14,
                       color=COLORS(z - 1), label=scenarios.ZONE_NAMES[z])
    eta = sep['eta_squared']
    ax.set(xscale='log', yscale='log', xlabel=f'{names[0]} (eta2 {eta[names[0]]:.2f})',
           ylabel=f'{names[1]} (eta2 {eta[names[1]]:.2f})', title=f'{name}: two most discriminative features')
    ax.legend(fontsize=8)
    ax.grid(alpha=0.3, which='both')
    fig.tight_layout()
    fig.savefig(path, dpi=120)
    plt.close(fig)


def plot_calibration(path, real, model, residual):
    t = np.arange(len(real)) * calibrate.SAMPLE_DT
    fig, ax = plt.subplots(figsize=(8, 4))
    ax.plot(t, real / 1000, 'o-', ms=3, label='real tail press (2026-09-20)')
    ax.plot(t, model / 1000, 's--', ms=3, label='lumped model (baseline)')
    ax.set(xlabel='time [s]', ylabel='delta counts / 1000',
           title=f'Calibration: weighted RMS residual {residual:.3f} (per-lobe normalised)')
    ax.legend()
    ax.grid(alpha=0.3)
    fig.tight_layout()
    fig.savefig(path, dpi=120)
    plt.close(fig)


def _pct(v):
    return 'n/a' if v != v else f'{100 * v:.0f} %'


def _row_text(rows, name):
    s = rows.get(name)
    return 'not run' if s is None else f"{_pct(s['acc4'])} 4-class / {_pct(s['acc7'])} 7-class"


def physics_caveat(rows):
    """Interpretation guard for the mech_* rows (only emitted when they were run)."""
    if not any(k.startswith('mech_') for k in rows):
        return []
    return ['## Physics caveat', '',
            'tau_in = c / k is the wall\'s retardation (sink-in) time. For a homogeneous TPU wall it is largely a '
            'material property: making a wall thicker or thinner changes k and c together and leaves c / k '
            f"unchanged. The mech_k_only row shows what stiffness alone buys ({_row_text(rows, 'mech_k_only')}). "
            f"The mech_tau rows (mech_tau4: {_row_text(rows, 'mech_tau4')}; mech_tau7_snap: "
            f"{_row_text(rows, 'mech_tau7_snap')}) show the upside only if geometry (domes, ribs, bellows, "
            'lattice-filled zones) can change the apparent sink-in time constant by 2x or more. That is what the '
            '10/16 test pieces must measure: width_ms and decay_ms per press-face type.', '',
            'Fluidic (channel) encoding is ruled out at 40 SPS: the star_graded channel delays are 4-15 ms, '
            'below one 25 ms sample (see the 1000 SPS table), so it would need kHz sampling.', '']


def summary_markdown(rows, high_rate, base, notes):
    lines = ['# Pneumatic lumped-parameter simulation', '',
             'Generated by `tools/pneumatic_sim.py run`. Simulated data only: 40 events per zone,',
             'randomised force/speed, Gaussian ADC noise, firmware 12-feature extraction,',
             'log + standardise, leave-one-out nearest centroid.', '',
             '| scenario | 7-class acc | 4-class acc | HEAD/LEGS acc | invalid | mean peak counts | mean trough counts | top-2 features |',
             '|---|---|---|---|---|---|---|---|']
    for name, s in rows.items():
        lines.append(f"| {name} | {_pct(s['acc7'])} | {_pct(s['acc4'])} | {_pct(s['acc_head_legs'])} | "
                     f"{_pct(s['invalid_rate'])} | {s['mean_peak_counts']:,.0f} | {s['mean_trough_counts']:,.0f} | "
                     f"{', '.join(top_two(s))} |")
    lines += ['', 'Chance level: 7-class 14 %, 4-class 25 % (majority LEGS 57 %), HEAD/LEGS 50 % (majority LEGS 80 %).', '']
    for name, table in high_rate.items():
        lines += [f'## {name}: 1000 SPS, no downsampling, noise-free sensor pressure', '',
                  '| zone | sensor rise 10-90 % [ms] | sensor lag behind pressed chamber at 50 % [ms] |',
                  '|---|---|---|']
        for z, r in table.items():
            lines.append(f"| {scenarios.ZONE_NAMES[z]} | {r['rise_ms_mean']:.1f} +/- {r['rise_ms_sd']:.1f} | "
                         f"{r['lag_ms_mean']:.2f} +/- {r['lag_ms_sd']:.2f} |")
        lines.append('')
    lines += physics_caveat(rows)
    lines += ['## Calibration', '',
              f'Baseline fitted to one real direct tail press; weighted RMS residual '
              f'{base.calibration_residual:.3f} (each lobe normalised by its own peak). See calibration.png.', '',
              '## Notes and approximations', ''] + [f'- {n}' for n in notes]
    return '\n'.join(lines) + '\n'


def write_parameters(path, payload):
    path.write_text(json.dumps(payload, indent=2, ensure_ascii=False, allow_nan=True), encoding='utf-8')
